-- Исправление первого набора: код 45 привязан к варианту УЛ, а не к модели лифта.
DELETE FROM fault_codes
WHERE controller_id IS NULL
  AND code IN ('45', 'E36')
  AND model_id IN (SELECT id FROM models WHERE name = '0401К');

DELETE FROM symptoms WHERE title = 'Остановка с ошибкой контроля тормоза или пускателя (УЛ 45, ПЧ E36)';

-- Лифт 0401К работает с УЛ ФБИР.484430.013 (проект электропривода 484430.013 Э4 назван в методике проверки тормоза) и ПЧ Hpmont.
INSERT IGNORE INTO model_controllers (model_id, controller_id)
SELECT m.id, c.id
FROM models m
JOIN controllers c ON c.name IN ('УЛ ФБИР.484430.013 (ГОСТ 33984.1, автоматические двери)', 'ПЧ Hpmont HD5L')
WHERE m.name = '0401К';
