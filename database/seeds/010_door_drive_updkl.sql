    UNION ALL SELECT 'Недостаточное усилие на створках дверей кабины', 'Восстановить лёгкий ход створок дверей кабины'
    UNION ALL SELECT 'Неисправен энкодер или датчик положения ротора привода дверей', 'Восстановить работу датчика положения ротора привода дверей'
