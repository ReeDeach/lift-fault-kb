-- Пересказ разделов 2.3 и 2.4 руководства на контроллер E-type (выпуск 1.0 от 12.01.04) своими словами.
-- Руководство переведено машинно, термины приведены к привычным:
--   «перебалансировка» — перевыравнивание (доводка кабины до уровня этажа),
--   «скорость поддержки» — скорость ревизии,
--   «предостановочные переключатели большой скорости» — замедлительные переключатели у крайних остановок.
-- Сообщения 01-49 контроллер называет неисправностями, 50-99 — событиями. Внесены только неисправности.
-- Причины, относящиеся только к гидравлическим лифтам (давление масла, клапаны), не внесены: лифт канатный.
-- Соглашения для раннера: в тексте нет точки с запятой и одинарных кавычек.

